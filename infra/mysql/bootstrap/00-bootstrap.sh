#!/bin/bash
set -Eeuo pipefail

required=(
  MYSQL_ROOT_PASSWORD
  FLOWDESK_GATEWAY_DB_PASSWORD
  FLOWDESK_IAM_DB_PASSWORD FLOWDESK_IAM_MIGRATOR_PASSWORD
  FLOWDESK_TICKET_DB_PASSWORD FLOWDESK_TICKET_MIGRATOR_PASSWORD
  FLOWDESK_WORKFLOW_DB_PASSWORD FLOWDESK_WORKFLOW_MIGRATOR_PASSWORD
  FLOWDESK_ALERT_DB_PASSWORD FLOWDESK_ALERT_MIGRATOR_PASSWORD
  FLOWDESK_NOTIFICATION_DB_PASSWORD FLOWDESK_NOTIFICATION_MIGRATOR_PASSWORD
  FLOWDESK_NOTIFICATION_RECOVERY_DB_PASSWORD
)

for name in "${required[@]}"; do
  value="${!name:-}"
  if [[ ! "$value" =~ ^[A-Za-z0-9_-]{16,128}$ ]] || [[ "$value" == change-* ]]; then
    echo "Invalid or placeholder secret: $name" >&2
    exit 1
  fi
done

MYSQL_PWD="${MYSQL_ROOT_PASSWORD}" mysql --protocol=socket -uroot <<SQL
CREATE DATABASE flowdesk_gateway CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE DATABASE flowdesk_iam CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE DATABASE flowdesk_ticket CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE DATABASE flowdesk_workflow CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE DATABASE flowdesk_alert CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE DATABASE flowdesk_notification CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;

CREATE USER 'fd_gateway_runtime'@'%' IDENTIFIED BY '${FLOWDESK_GATEWAY_DB_PASSWORD}';
CREATE USER 'fd_iam_runtime'@'%' IDENTIFIED BY '${FLOWDESK_IAM_DB_PASSWORD}';
CREATE USER 'fd_iam_migrator'@'%' IDENTIFIED BY '${FLOWDESK_IAM_MIGRATOR_PASSWORD}';
CREATE USER 'fd_ticket_runtime'@'%' IDENTIFIED BY '${FLOWDESK_TICKET_DB_PASSWORD}';
CREATE USER 'fd_ticket_migrator'@'%' IDENTIFIED BY '${FLOWDESK_TICKET_MIGRATOR_PASSWORD}';
CREATE USER 'fd_workflow_runtime'@'%' IDENTIFIED BY '${FLOWDESK_WORKFLOW_DB_PASSWORD}';
CREATE USER 'fd_workflow_migrator'@'%' IDENTIFIED BY '${FLOWDESK_WORKFLOW_MIGRATOR_PASSWORD}';
CREATE USER 'fd_alert_runtime'@'%' IDENTIFIED BY '${FLOWDESK_ALERT_DB_PASSWORD}';
CREATE USER 'fd_alert_migrator'@'%' IDENTIFIED BY '${FLOWDESK_ALERT_MIGRATOR_PASSWORD}';
CREATE USER 'fd_notification_runtime'@'%' IDENTIFIED BY '${FLOWDESK_NOTIFICATION_DB_PASSWORD}';
CREATE USER 'fd_notification_migrator'@'%' IDENTIFIED BY '${FLOWDESK_NOTIFICATION_MIGRATOR_PASSWORD}';
CREATE USER 'fd_notification_recovery'@'%' IDENTIFIED BY '${FLOWDESK_NOTIFICATION_RECOVERY_DB_PASSWORD}';

GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, DROP, INDEX, REFERENCES, TRIGGER
  ON flowdesk_iam.* TO 'fd_iam_migrator'@'%';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, DROP, INDEX, REFERENCES, TRIGGER
  ON flowdesk_ticket.* TO 'fd_ticket_migrator'@'%';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, DROP, INDEX, REFERENCES, TRIGGER
  ON flowdesk_workflow.* TO 'fd_workflow_migrator'@'%';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, DROP, INDEX, REFERENCES, TRIGGER
  ON flowdesk_alert.* TO 'fd_alert_migrator'@'%';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, DROP, INDEX, REFERENCES, TRIGGER
  ON flowdesk_notification.* TO 'fd_notification_migrator'@'%';
SQL
