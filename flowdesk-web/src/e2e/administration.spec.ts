 await page.getByRole('button',{name:'创建用户',exact:true}).click()
 const row=page.locator('tbody tr').filter({hasText:'new-colleague'})
 await expect(row).toBeVisible()
 await row.getByRole('button',{name:'分配角色'}).click()
 await expect(page.getByRole('dialog')).toBeInViewport({ratio:1})
 await page.getByRole('dialog').getByLabel('申请人',{exact:true}).check()
 await page.getByRole('button',{name:'完成',exact:true}).click()
 await expect(row).toContainText('申请人')
 await row.getByRole('button',{name:'停用账号'}).click()
 await expect(row.getByRole('button',{name:'恢复账号'})).toBeVisible()
 await row.getByRole('button',{name:'恢复账号'}).click()
 await expect(row.getByRole('button',{name:'停用账号'})).toBeVisible()
 await page.screenshot({path:`artifacts/playwright/administration/${test.info().project.name}-users.png`,fullPage:true})
