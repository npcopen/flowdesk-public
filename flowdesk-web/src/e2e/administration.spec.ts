test('service desk admin creates catalog types and explicitly activates an approval version',async({page})=>{
 await login(page,'admin');await settings(page,'工单类型')
 await page.getByRole('button',{name:'新增类型',exact:true}).click()
 await page.getByLabel('类型编码').fill('DISPLAY_REQUEST');await page.getByLabel('类型名称').fill('外接显示器申请')
 await page.getByLabel('服务说明').fill('为员工申请办公显示器')
 await page.getByRole('button',{name:'保存类型',exact:true}).click()
 const row=page.locator('tbody tr').filter({hasText:'DISPLAY_REQUEST'})
 await expect(row).toContainText('无需审批')
 await row.getByRole('button',{name:'配置类型'}).click()
 await page.getByLabel('风险级别').selectOption('HIGH')
 await page.getByLabel('生效审批版本').selectOption({index:1})
 await expect(page.getByRole('dialog')).toBeInViewport({ratio:1})
 await page.screenshot({path:`artifacts/playwright/administration/${test.info().project.name}-catalog-edit.png`,fullPage:false})
 await page.getByRole('button',{name:'保存类型',exact:true}).click()
 await expect(row).toContainText('高风险')
 await expect(row).toContainText('第 1 版')
 await page.screenshot({path:`artifacts/playwright/administration/${test.info().project.name}-catalog.png`,fullPage:true})
 await row.getByRole('button',{name:'配置类型'}).click();await page.getByRole('combobox',{name:'状态',exact:true}).selectOption('INACTIVE')
 await page.getByRole('button',{name:'保存类型',exact:true}).click();await expect(row).toContainText('已停用')
})
